use std::sync::Arc;

use base64::Engine as _;
use hmac::{Hmac, KeyInit, Mac};
use sha1::Sha1;

use super::generate_auth_key;
use super::internal::auth::{AuthHandler, RequestAttributes};
use crate::go::time::{self, Duration};
use crate::protocol::logger::Logger;

// GenerateLongTermCredentials can be used to create credentials valid for [duration] time.
pub fn generate_long_term_credentials(shared_secret: &str, duration: Duration) -> (String, String) {
    let t = (time::now() + duration).unix_secs();
    let username = t.to_string();
    let password = long_term_credentials(&username, shared_secret);

    (username, password)
}

// GenerateLongTermTURNRESTCredentials can be used to create credentials valid for [duration] time.
pub fn generate_long_term_turn_rest_credentials(
    shared_secret: &str,
    user: &str,
    duration: Duration,
) -> (String, String) {
    let t = (time::now() + duration).unix_secs();
    let timestamp = t.to_string();
    let username = timestamp + ":" + user;
    let password = long_term_credentials(&username, shared_secret);

    (username, password)
}

pub(crate) fn long_term_credentials(username: &str, shared_secret: &str) -> String {
    let mut mac = Hmac::<Sha1>::new_from_slice(shared_secret.as_bytes())
        .expect("HMAC takes a key of any length");
    mac.update(username.as_bytes());
    let password = mac.finalize().into_bytes();

    base64::engine::general_purpose::STANDARD.encode(password)
}

// NewLongTermAuthHandler returns a turn.AuthAuthHandler used with Long Term (or Time Windowed) Credentials.
// See: https://datatracker.ietf.org/doc/html/rfc8489#section-9.2
// .
pub fn new_long_term_auth_handler(shared_secret: &str, logger: Option<Logger>) -> AuthHandler {
    let logger = logger.unwrap_or_default().with_name("turn");
    let shared_secret = shared_secret.to_string();

    Arc::new(move |ra: &RequestAttributes| {
        debugf!(
            logger,
            "Authentication username={:?} realm={:?} srcAddr={}",
            ra.username,
            ra.realm,
            ra.src_addr
        );
        let Ok(t) = ra.username.parse::<i64>() else {
            errorf!(logger, "Invalid time-windowed username {:?}", ra.username);

            return (String::new(), Vec::new(), false);
        };
        if t < time::now().unix_secs() {
            errorf!(logger, "Expired time-windowed username {:?}", ra.username);

            return (String::new(), Vec::new(), false);
        }
        let password = long_term_credentials(&ra.username, &shared_secret);

        (
            ra.username.clone(),
            generate_auth_key(&ra.username, &ra.realm, &password),
            true,
        )
    })
}

// LongTermTURNRESTAuthHandler returns a turn.AuthAuthHandler that can be used to authenticate
// time-windowed ephemeral credentials generated by the TURN REST API as described in
// https://datatracker.ietf.org/doc/html/draft-uberti-behave-turn-rest-00
//
// The supported format of is timestamp:username, where username is an arbitrary user id and the
// timestamp specifies the expiry of the credential.
pub fn long_term_turn_rest_auth_handler(
    shared_secret: &str,
    logger: Option<Logger>,
) -> AuthHandler {
    let logger = logger.unwrap_or_default().with_name("turn");
    let shared_secret = shared_secret.to_string();

    Arc::new(move |ra: &RequestAttributes| {
        debugf!(
            logger,
            "Authentication username={:?} realm={:?} srcAddr={}",
            ra.username,
            ra.realm,
            ra.src_addr
        );

        // Parse timestamp and userID. Set userID to the full username if the id cannot be
        // parsed.
        let fields: Vec<&str> = ra.username.split(':').collect();
        let timestamp = fields[0];
        let mut user_id = ra.username.as_str();
        if fields.len() > 1 {
            user_id = fields[1];
        }

        let Ok(t) = timestamp.parse::<i64>() else {
            errorf!(logger, "Invalid time-windowed username {:?}", ra.username);

            return (String::new(), Vec::new(), false);
        };
        if t < time::now().unix_secs() {
            errorf!(logger, "Expired time-windowed username {:?}", ra.username);

            return (String::new(), Vec::new(), false);
        }
        let password = long_term_credentials(&ra.username, &shared_secret);

        (
            user_id.to_string(),
            generate_auth_key(&ra.username, &ra.realm, &password),
            true,
        )
    })
}

